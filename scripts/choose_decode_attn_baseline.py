"""Choose the decode_attn baseline by measurement, not by assumption.

For each PyTorch SDPA backend (flash, cudnn, efficient, math) this script:
  1. probes whether the backend runs on this GPU for the target shape, both with
     enable_gqa=True and with the KV heads repeated by repeat_interleave;
  2. times it under the target's own contract with bench(n=5) through
     examples/decode_attn_backends.py (same inputs, seed, rotation and fp32 reference check
     as the baseline);
and writes results/decode_attn/baseline_choice.json plus a section in
results/decode_attn/log.md. The chosen backend is the fastest mean among those that run and
pass the reference check. The baseline file itself is then regenerated by hand:

    hotkernel new decode_attn --from decode_attn_sdpa:attn_<chosen> ... --force

Run from the repo root with the interpreter the server uses:
    HOTKERNEL_PYTHON=<torch python> uv run python scripts/choose_decode_attn_baseline.py
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from hotkernel import server

BACKENDS = ("flash", "cudnn", "efficient", "math")
PATH_USED = {
    "flash": "enable_gqa=True",
    "cudnn": "enable_gqa=True",
    "efficient": "repeat_interleave KV x4 (enable_gqa=True is rejected for this shape)",
    "math": "enable_gqa=True",
}
MEASURED_MEM_GBS = 1501.0  # best streaming kernel measured on this card under protocol 3

PROBE = r"""
import json, sys, warnings
warnings.simplefilter("ignore")
sys.path.insert(0, sys.argv[1])
import torch
import decode_attn_sdpa as m
from torch.nn.attention import SDPBackend
torch.manual_seed(0)
q = torch.randn(1, 32, 1, 128, device="cuda", dtype=torch.bfloat16)
k = torch.randn(1, 8, 32768, 128, device="cuda", dtype=torch.bfloat16)
v = torch.randn_like(k)
names = {"flash": SDPBackend.FLASH_ATTENTION, "cudnn": SDPBackend.CUDNN_ATTENTION,
         "efficient": SDPBackend.EFFICIENT_ATTENTION, "math": SDPBackend.MATH}
out = {}
for name, be in names.items():
    row = {}
    for mode, fn in (("enable_gqa", m._sdpa), ("repeat_interleave", m._sdpa_repeat)):
        try:
            fn(be, q, k, v)
            torch.cuda.synchronize()
            row[mode] = "ok"
        except Exception as e:  # noqa: BLE001
            row[mode] = "error: " + (str(e).splitlines() or [""])[0][:160]
    out[name] = row
out["_env"] = {"gpu": torch.cuda.get_device_name(0),
               "capability": list(torch.cuda.get_device_capability(0)),
               "torch": torch.__version__, "cudnn": torch.backends.cudnn.version()}
print("PROBE " + json.dumps(out))
"""


def probe(python: str) -> dict:
    p = subprocess.run([python, "-c", PROBE, str(ROOT / "examples")], capture_output=True,
                       text=True, timeout=600, check=False)
    for line in reversed(p.stdout.splitlines()):
        if line.startswith("PROBE "):
            return json.loads(line[6:])
    raise SystemExit(f"probe failed (rc={p.returncode}):\n{p.stderr[-2000:]}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=5)
    ap.add_argument("--out", default=str(ROOT / "results" / "decode_attn"))
    a = ap.parse_args(argv)

    python, err = server._python_or_error()
    if err:
        raise SystemExit(json.dumps(err))

    avail = probe(python)
    env = avail.pop("_env")
    script = str(ROOT / "examples" / "decode_attn_backends.py")

    rows: dict[str, dict] = {}
    for be in BACKENDS:
        r = server.bench(script, n=a.n, args=["--backend", be], timeout=900)
        if "error" in r:
            d = r.get("detail")
            tail = (d.get("stderr", "") if isinstance(d, dict) else str(d or ""))[-400:]
            rows[be] = {"path_used": PATH_USED[be], "runs": False, "all_ok": False,
                        "error": r["error"], "stderr_tail": tail}
            print(f"{be:9s} ERROR {r['error'][:100]}")
            continue
        s0 = r["samples"][0]
        rows[be] = {
            "path_used": PATH_USED[be], "runs": True, "all_ok": r["all_ok"],
            "n": r["n"], "mean_ms": r["mean_ms"], "std_ms": r["std_ms"],
            "min_ms": r["min_ms"], "max_ms": r["max_ms"],
            "samples_ms": [s["ms"] for s in r["samples"]],
            "achieved_gbs_lower_bound": s0.get("achieved_gbs_lower_bound"),
            "min_bytes": s0.get("min_bytes"), "rotation_k": s0.get("rotation_k"),
            "impl": s0.get("impl"),
        }
        print(f"{be:9s} mean {r['mean_ms']:.4f} ms  std {r['std_ms']:.4f}  min {r['min_ms']:.4f}"
              f"  ok={r['all_ok']}  >= {s0.get('achieved_gbs_lower_bound')} GB/s")

    ok = {be: v for be, v in rows.items() if v.get("runs") and v.get("all_ok")}
    if not ok:
        raise SystemExit("no backend both runs and passes the fp32 reference check")
    chosen = min(ok, key=lambda be: ok[be]["mean_ms"])
    min_bytes = next((v["min_bytes"] for v in ok.values() if v.get("min_bytes")), None)
    floor_ms = (min_bytes / (MEASURED_MEM_GBS * 1e9) * 1e3) if min_bytes else None

    out_dir = pathlib.Path(a.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    choice = {
        "target": "decode_attn",
        "date": dt.date.today().isoformat(),
        "gpu": env["gpu"], "capability": env["capability"],
        "torch": env["torch"], "cudnn": env["cudnn"],
        "protocol": 3, "bench_n": a.n,
        "availability_on_this_gpu": avail,
        "backends": rows,
        "chosen": chosen,
        "chosen_mean_ms": ok[chosen]["mean_ms"],
        "reason": (f"fastest mean over bench n={a.n} among backends that run on this GPU and "
                   "pass the fp32 reference check (bf16 default tolerances)"),
        "min_bytes": min_bytes,
        "measured_mem_gbs": MEASURED_MEM_GBS,
        "floor_ms_at_measured_bandwidth": floor_ms,
        "chosen_pct_of_measured_bandwidth": (
            round(100 * floor_ms / ok[chosen]["mean_ms"], 1) if floor_ms else None),
    }
    (out_dir / "baseline_choice.json").write_text(json.dumps(choice, indent=1) + "\n")

    cap = "sm_{}{}".format(*env["capability"])
    lines = [
        (f"## Baseline choice ({choice['date']}, {env['gpu']}, {cap}, torch {env['torch']}, "
         f"cuDNN {env['cudnn']})"),
        "",
        ("q (1,32,1,128), k/v (1,8,32768,128), bf16; reference = fp32 math attention; "
         f"protocol 3, bench n={a.n}. Written by scripts/choose_decode_attn_baseline.py; raw "
         "numbers in baseline_choice.json."),
        "",
        (f"| backend | runs on {cap}? (enable_gqa / repeat_interleave) | path timed | mean ms | "
         "std ms | min ms | correct | >= GB/s |"),
        "|---|---|---|---|---|---|---|---|",
    ]
    for be in BACKENDS:
        v = rows[be]
        av = avail[be]
        a1 = "yes" if av["enable_gqa"] == "ok" else "no"
        a2 = "yes" if av["repeat_interleave"] == "ok" else "no"
        if v.get("runs"):
            lines.append(f"| {be} | {a1} / {a2} | {v['path_used']} | {v['mean_ms']:.4f} | "
                         f"{v['std_ms']:.4f} | {v['min_ms']:.4f} | {v['all_ok']} | "
                         f"{v['achieved_gbs_lower_bound']} |")
        else:
            lines.append(f"| {be} | {a1} / {a2} | {v['path_used']} | - | - | - | did not run | - |")
    lines += [
        "",
        f"Chosen baseline: **{chosen}** ({ok[chosen]['mean_ms']:.4f} ms mean), {choice['reason']}.",
    ]
    if floor_ms:
        lines.append(f"Floor at the measured {MEASURED_MEM_GBS:.0f} GB/s for {min_bytes} B: "
                     f"{floor_ms:.4f} ms; the chosen baseline is at "
                     f"{choice['chosen_pct_of_measured_bandwidth']}% of it.")
    for be in BACKENDS:
        for mode, msg in avail[be].items():
            if msg != "ok":
                lines.append(f"- {be} / {mode}: {msg}")
    lines.append("")
    log = out_dir / "log.md"
    head = "" if log.exists() else "# decode_attn\n\n"
    with log.open("a", encoding="utf-8", newline="\n") as f:
        f.write(head + "\n".join(lines) + "\n")
    print("chosen:", chosen)
    return 0


if __name__ == "__main__":
    sys.exit(main())
