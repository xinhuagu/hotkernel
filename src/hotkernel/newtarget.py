"""Scaffold a hotkernel target from the user's own PyTorch function.

Used by the `hotkernel new` command and the `new_target` MCP tool. It writes three files into
the output directory, none of which import hotkernel, so they run in whatever interpreter has
the user's PyTorch:

  _hotkernel_contract.py   the vendored contract (protocol 3 timer, Target, tolerances)
  <target>_baseline.py     the user's function as the baseline, plus the Target definition
  <target>_candidate.py    the file the loop edits; starts as the baseline

This module imports no torch: the generated scripts do.
"""

from __future__ import annotations

import argparse
import importlib.resources
import json
import re
import sys
import time
from pathlib import Path

CONTRACT_FILE = "_hotkernel_contract.py"
_NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")
_INPUT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def contract_source() -> str:
    """The contract file as shipped in this hotkernel version."""
    return (importlib.resources.files("hotkernel").joinpath("templates/contract.py")
            .read_text(encoding="utf-8"))


def contract_protocol() -> int:
    m = re.search(r"^PROTOCOL\s*=\s*(\d+)", contract_source(), re.MULTILINE)
    return int(m.group(1)) if m else 0


def parse_shape(spec: str) -> tuple[int, ...]:
    """'4096x8192', '4096,8192' or '8192' -> tuple of ints."""
    parts = [p for p in re.split(r"[x,*]", str(spec).strip().lower()) if p]
    try:
        dims = tuple(int(p) for p in parts)
    except ValueError:
        raise ValueError(f"bad shape {spec!r}; write it like 4096x8192") from None
    if not dims or any(d <= 0 for d in dims):
        raise ValueError(f"bad shape {spec!r}; every dimension must be a positive integer")
    return dims


def parse_inputs(shape: str, extra: list[str] | None) -> dict[str, tuple[int, ...]]:
    """The primary input is `x` with `shape`; extras are 'name:shape' items in call order."""
    shapes = {"x": parse_shape(shape)}
    for item in extra or []:
        if ":" not in item:
            raise ValueError(f"extra input {item!r} must look like name:shape, e.g. w:8192")
        name, s = item.split(":", 1)
        if not _INPUT_RE.match(name) or name in shapes:
            raise ValueError(f"bad or duplicate input name {name!r}")
        shapes[name] = parse_shape(s)
    return shapes


def parse_from(spec: str) -> tuple[str, str, bool]:
    """'torch.nn.functional:gelu' -> (module, function, False);
    'mykernels.py:fused' or './dir/k.py:f' -> (file path, function, True)."""
    if ":" not in spec:
        raise ValueError(f"--from must be module:function or file.py:function, got {spec!r}")
    module, function = spec.rsplit(":", 1)
    if not _INPUT_RE.match(function):
        raise ValueError(f"bad function name {function!r}")
    is_file = module.endswith(".py")
    if not is_file and not re.match(r"^[A-Za-z_][\w.]*$", module):
        raise ValueError(f"bad module name {module!r}")
    return module, function, is_file


_BASELINE = '''"""hotkernel target "{target}": {spec} is the baseline.

Generated by `hotkernel new` on {date} (contract protocol {protocol}). Everything that makes
the number honest is here and in {contract}: the inputs (shapes, dtype, seed), the reference
and its tolerances, the input rotation and the timer. A candidate defines a function with the
same signature and calls run(candidate, impl="..."); it cannot change any of this without
changing the contract fields that verify() checks. The loop never edits this file.

The reference is the same function run in fp32 and cast back to DTYPE. If your function
needs a different reference (a different formula, a library call), edit `reference` below
before the first verify(), not after.
"""

{binding}
from _hotkernel_contract import PROTOCOL, Target  # noqa: E402

DTYPE = {dtype!r}
SHAPES = {shapes}  # inputs in call order
ROTATE = {rotate}  # streamed inputs that get K distinct copies (> 2x L2 in total)
ITERS = {iters}
SEED = {seed}
RTOL, ATOL = {rtol}, {atol}  # None = default for DTYPE (see DEFAULT_TOLERANCES in the contract)
FLOPS = {flops}  # nominal flops per call for roofline(); None = not stated

assert PROTOCOL == {protocol}, "contract file does not match the protocol this target was generated for"


def reference({params}):
    return baseline_fn({float_args}).to({primary}.dtype)


TARGET = Target(name={target!r}, dtype=DTYPE, shapes=SHAPES, rotate=ROTATE, reference=reference,
                rtol=RTOL, atol=ATOL, iters=ITERS, seed=SEED, flops=FLOPS,
                reference_name={refname!r})


def run(fn, impl: str, extra: dict | None = None) -> None:
    TARGET.run(fn, impl, extra)


if __name__ == "__main__":
    run(baseline_fn, impl={spec!r})
'''

_CANDIDATE = '''"""Candidate for the "{target}" target: the file the kernel-speedrun loop edits.

It starts as the baseline itself, so the first verify() is a fair "inconclusive" and every
later verdict measures only what changed. Define {target}_candidate({params}) and leave the
run() call alone: inputs, seed, reference, tolerances, rotation and timer are the baseline's,
and verify() reports `invalid` if the contract changes. Triton and torch.compile are fair game.
"""

from {target}_baseline import baseline_fn, run


def {target}_candidate({params}):
    # Starting point: the baseline. Replace with something faster; keep the signature.
    return baseline_fn({params})


if __name__ == "__main__":
    run({target}_candidate, impl="candidate (starts as the baseline)")
'''

_BIND_MODULE = '''import importlib

import torch  # noqa: F401  (the generated scripts run in the interpreter that has your torch)

baseline_fn = getattr(importlib.import_module({module!r}), {function!r})'''

_BIND_FILE = '''import importlib.util
import sys

import torch  # noqa: F401  (the generated scripts run in the interpreter that has your torch)

_spec = importlib.util.spec_from_file_location({modname!r}, {path!r})
_mod = importlib.util.module_from_spec(_spec)
sys.modules[{modname!r}] = _mod
_spec.loader.exec_module(_mod)
baseline_fn = getattr(_mod, {function!r})'''


def new_target(target: str, from_: str, shape: str, dtype: str = "bf16",
               extra: list[str] | None = None, rotate: list[str] | None = None,
               out_dir: str = ".", flops: int | None = None, iters: int = 50, seed: int = 0,
               rtol: float | None = None, atol: float | None = None, force: bool = False) -> dict:
    """Write the three files and return what was written plus the next commands. Errors come
    back as {"error": ...} so an agent can read them."""
    try:
        if not _NAME_RE.match(target):
            raise ValueError(f"target name {target!r} must be lowercase letters, digits and _")
        shapes = parse_inputs(shape, extra)
        module, function, is_file = parse_from(from_)
        rotate_names = tuple(rotate) if rotate else ("x",)
        if any(r not in shapes for r in rotate_names):
            raise ValueError(f"--rotate names must be inputs: {list(shapes)}")
    except ValueError as e:
        return {"error": str(e)}

    out = Path(out_dir).expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)
    contract = out / CONTRACT_FILE
    baseline = out / f"{target}_baseline.py"
    candidate = out / f"{target}_candidate.py"
    src = contract_source()
    if contract.exists() and contract.read_text(encoding="utf-8") != src and not force:
        return {"error": f"{contract} exists and differs from this hotkernel's contract "
                         f"(protocol {contract_protocol()}); pass force=True / --force to replace "
                         "it, which re-times every target in that directory under the new contract"}
    clashes = [str(p) for p in (baseline, candidate) if p.exists()]
    if clashes and not force:
        return {"error": f"already exists: {clashes}; pass force=True / --force to overwrite"}

    params = ", ".join(shapes)
    primary = rotate_names[0]
    if is_file:
        path = str(Path(module).expanduser().resolve())
        modname = "_hk_user_" + re.sub(r"\W", "_", Path(module).stem)
        binding = _BIND_FILE.format(modname=modname, path=path, function=function)
        spec = f"{Path(module).name}:{function}"
    else:
        binding = _BIND_MODULE.format(module=module, function=function)
        spec = f"{module}:{function}"
    protocol = contract_protocol()
    baseline_text = _BASELINE.format(
        target=target, spec=spec, date=time.strftime("%Y-%m-%d"), protocol=protocol,
        contract=CONTRACT_FILE, binding=binding, dtype=dtype,
        shapes="{" + ", ".join(f"{n!r}: {s!r}" for n, s in shapes.items()) + "}",
        rotate=repr(tuple(rotate_names)), iters=int(iters), seed=int(seed),
        rtol=repr(rtol), atol=repr(atol), flops=repr(None if flops is None else int(flops)),
        params=params, float_args=", ".join(f"{n}.float()" for n in shapes), primary=primary,
        refname=f"{spec} in fp32")
    candidate_text = _CANDIDATE.format(target=target, params=params)

    contract.write_text(src, encoding="utf-8", newline="\n")
    baseline.write_text(baseline_text, encoding="utf-8", newline="\n")
    candidate.write_text(candidate_text, encoding="utf-8", newline="\n")
    rel = out.as_posix()
    return {
        "target": target, "protocol": protocol,
        "files": {"contract": str(contract), "baseline": str(baseline), "candidate": str(candidate)},
        "inputs": {n: list(s) for n, s in shapes.items()}, "dtype": dtype, "rotate": list(rotate_names),
        "next": [
            (f"python {baseline.name} (run from {rel}, in the interpreter that has your torch) "
             "to see the baseline's JSON line"),
            f"bench(script='{rel}/{baseline.name}', n=5): the number to beat",
            (f"verify(candidate='{rel}/{candidate.name}', baseline='{rel}/{baseline.name}', n=7): "
             "must be 'inconclusive' before you change anything"),
            f"edit {candidate.name}, then verify() and record(target='{target}', ...) after every change",
        ],
    }


def build_parser(prog: str = "hotkernel new") -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog=prog, description="Scaffold a hotkernel target from your "
                                "own PyTorch function: baseline, blank candidate and the vendored contract.")
    p.add_argument("target", help="target name, e.g. gelu (lowercase letters, digits, _)")
    p.add_argument("--from", dest="from_", required=True, metavar="MODULE:FUNCTION",
                   help="the function to speed up: torch.nn.functional:gelu or ./mykernels.py:fused")
    p.add_argument("--shape", required=True, help="shape of the primary input x, e.g. 4096x8192")
    p.add_argument("--dtype", default="bf16", help="bf16 (default), fp16, fp32, fp64")
    p.add_argument("--extra", nargs="*", default=[], metavar="NAME:SHAPE",
                   help="more inputs in call order, e.g. w:8192 b:8192 (random, same dtype)")
    p.add_argument("--rotate", nargs="*", default=None, metavar="NAME",
                   help="inputs that stream through memory and get K copies (default: x)")
    p.add_argument("--out", default=".", help="directory for the generated files (default: .)")
    p.add_argument("--flops", type=int, default=None, help="nominal flops per call for roofline()")
    p.add_argument("--iters", type=int, default=50)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--rtol", type=float, default=None, help="override the dtype default")
    p.add_argument("--atol", type=float, default=None, help="override the dtype default")
    p.add_argument("--force", action="store_true", help="overwrite existing files")
    return p


def main(argv: list[str]) -> int:
    args = build_parser().parse_args(argv)
    result = new_target(args.target, args.from_, args.shape, args.dtype, args.extra, args.rotate,
                        args.out, args.flops, args.iters, args.seed, args.rtol, args.atol, args.force)
    print(json.dumps(result, indent=1))
    return 1 if "error" in result else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
